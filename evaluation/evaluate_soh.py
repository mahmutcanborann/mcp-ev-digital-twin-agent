"""Reproducible comparison of SOH approaches.

Writes evaluation/results.md and evaluation/results.json.

Protocol
--------
* Notebook method: random 80/20 row split, inputs (battery_id, temperature, cycle).
  Rows of the same battery end up in both train and test -> optimistic.
* Leave-one-battery-out (LOBO): train on all batteries but one, test on the
  held-out battery, repeat for every battery. This is what "works on a new
  battery" means.

Usage:
    python evaluation/evaluate_soh.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import GroupKFold, train_test_split

BASE_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BASE_DIR))

from src.soh_estimator import MIN_CYCLES_PER_BATTERY, make_model  # noqa: E402
from src.soh_features import CHARGE_FEATURES, DISCHARGE_FEATURES  # noqa: E402

DATASET = BASE_DIR / "data" / "features" / "soh_dataset.csv"
OUT_DIR = BASE_DIR / "evaluation"

LOBO_SETS = {
    "Original project inputs (temperature + cycle)": ["ambient_temperature", "cycle"],
    "Charge window 3.9-4.2 V + CV time": ["ambient_temperature"] + CHARGE_FEATURES,
    "First 5 min of discharge (production model)": DISCHARGE_FEATURES,
    "Charge + first 5 min of discharge": DISCHARGE_FEATURES + CHARGE_FEATURES,
}


def metrics(y, p) -> dict:
    return {
        "mae": round(float(mean_absolute_error(y, p)), 2),
        "rmse": round(float(np.sqrt(mean_squared_error(y, p))), 2),
        "r2": round(float(r2_score(y, p)), 3),
    }


def lobo(data: pd.DataFrame, features: list[str]) -> np.ndarray:
    y = data["SOH"].to_numpy()
    pred = np.zeros(len(data))
    for tr, te in GroupKFold(n_splits=data["battery_id"].nunique()).split(data, y, data["battery_id"]):
        pred[te] = make_model().fit(data.iloc[tr][features], y[tr]).predict(data.iloc[te][features])
    return pred


def main() -> None:
    df = pd.read_csv(DATASET)
    df["battery_code"] = df["battery_id"].astype("category").cat.codes
    long = df[df.groupby("battery_id")["cycle"].transform("size") >= MIN_CYCLES_PER_BATTERY].reset_index(drop=True)

    results = {"dataset": {"cycles": len(df), "batteries": int(df.battery_id.nunique()),
                           "long_batteries": int(long.battery_id.nunique()), "long_cycles": len(long)}}

    # notebook method (random split, battery id as input) - for reference
    X = df[["battery_code", "ambient_temperature", "cycle"]]
    Xtr, Xte, ytr, yte = train_test_split(X, df["SOH"], test_size=0.2, random_state=42)
    rf = RandomForestRegressor(n_estimators=300, random_state=42, n_jobs=-1).fit(Xtr, ytr)
    results["notebook_random_split"] = metrics(yte, rf.predict(Xte))
    print("notebook random split:", results["notebook_random_split"])

    results["lobo"] = {}
    best_pred = None
    for subset_name, data in [("all_batteries", df), ("batteries_with_40plus_cycles", long)]:
        results["lobo"][subset_name] = {}
        for name, feats in LOBO_SETS.items():
            p = lobo(data, feats)
            results["lobo"][subset_name][name] = metrics(data["SOH"], p)
            print(subset_name, "|", name, results["lobo"][subset_name][name])
            if subset_name == "batteries_with_40plus_cycles" and feats == DISCHARGE_FEATURES:
                best_pred = p

    per_battery = (long.assign(abs_err=np.abs(long["SOH"] - best_pred))
                   .groupby("battery_id")["abs_err"].mean().round(2).sort_values())
    results["production_model_per_battery_mae"] = per_battery.to_dict()

    (OUT_DIR / "results.json").write_text(json.dumps(results, indent=2))
    write_markdown(results, per_battery)
    print("wrote evaluation/results.md and evaluation/results.json")


def write_markdown(r: dict, per_battery: pd.Series) -> None:
    ds = r["dataset"]
    lines = [
        "# SOH model evaluation",
        "",
        "Generated by `python evaluation/evaluate_soh.py`. Target: SOH = capacity / battery's max capacity x 100.",
        f"Data: NASA PCoE battery dataset, {ds['cycles']} discharge cycles from {ds['batteries']} batteries "
        f"({ds['long_batteries']} batteries / {ds['long_cycles']} cycles with >= {MIN_CYCLES_PER_BATTERY} cycles).",
        "",
        "## Random split vs. unseen battery",
        "",
        "| Evaluation | Inputs | MAE (SOH pts) | RMSE (SOH pts) | R² |",
        "|---|---|---|---|---|",
        f"| Random 80/20 row split (notebook) | battery ID, temperature, cycle | "
        f"{r['notebook_random_split']['mae']} | {r['notebook_random_split']['rmse']} | "
        f"{r['notebook_random_split']['r2']} |",
    ]
    for name, m in r["lobo"]["batteries_with_40plus_cycles"].items():
        lines.append(f"| Leave-one-battery-out | {name} | {m['mae']} | {m['rmse']} | {m['r2']} |")
    lines += ["", "## Leave-one-battery-out, all batteries (incl. short, noisy ones)", "",
              "| Inputs | MAE (SOH pts) | RMSE (SOH pts) | R² |", "|---|---|---|---|"]
    for name, m in r["lobo"]["all_batteries"].items():
        lines.append(f"| {name} | {m['mae']} | {m['rmse']} | {m['r2']} |")
    lines += ["", "## Production model: error per held-out battery", "",
              "| Battery | MAE (SOH pts) |", "|---|---|"]
    lines += [f"| {b} | {e} |" for b, e in per_battery.items()]
    (OUT_DIR / "results.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
